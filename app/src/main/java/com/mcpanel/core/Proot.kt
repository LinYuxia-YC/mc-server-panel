package com.mcpanel.core

import android.content.Context
import android.net.ConnectivityManager
import java.io.File

/**
 * proot based portable Linux environment. proot, libtalloc and libandroid-shmem are bundled
 * inside the APK (they are tiny), the Ubuntu rootfs and Temurin JREs are downloaded.
 */
object Proot {

    private const val ASSET_PROOT = "proot/bin/proot"
    private const val ASSET_LOADER = "proot/libexec/proot/loader"
    private const val ASSET_LOADER32 = "proot/libexec/proot/loader32"
    private const val ASSET_TALLOC = "proot/lib/libtalloc.so.2"
    private const val ASSET_SHMEM = "proot/lib/libandroid-shmem.so"

    fun binary(): File = File(Paths.prootEnvDir, "bin/proot")
    fun loader(): File = File(Paths.prootEnvDir, "libexec/proot/loader")
    fun libDir(): File = File(Paths.prootEnvDir, "lib")

    fun isEnvReady(): Boolean = binary().exists() && File(Paths.rootfs, "bin/sh").exists()

    fun copyBundledBinaries(ctx: Context) {
        Paths.ensure()
        val targets = listOf(
            ASSET_PROOT to binary(),
            ASSET_LOADER to loader(),
            ASSET_LOADER32 to File(Paths.prootEnvDir, "libexec/proot/loader32"),
            ASSET_TALLOC to File(libDir(), "libtalloc.so.2"),
            ASSET_SHMEM to File(libDir(), "libandroid-shmem.so")
        )
        targets.forEach { (asset, target) ->
            FileUtils.ensureDir(target.parentFile ?: return@forEach)
            if (!target.exists() || target.length() == 0L) {
                try {
                    ctx.assets.open(asset).use { input ->
                        target.outputStream().use { output -> input.copyTo(output) }
                    }
                } catch (_: Throwable) {
                }
            }
        }
        binary().setExecutable(true, false)
        loader().setExecutable(true, false)
        File(Paths.prootEnvDir, "libexec/proot/loader32").setExecutable(true, false)
        File(libDir(), "libtalloc.so.2").setReadable(true, false)
        File(libDir(), "libandroid-shmem.so").setReadable(true, false)
    }

    fun env(): MutableMap<String, String> {
        val map = mutableMapOf<String, String>()
        map["LD_LIBRARY_PATH"] = libDir().absolutePath
        map["PROOT_LOADER"] = loader().absolutePath
        map["PROOT_TMP_DIR"] = Paths.prootTmp.absolutePath
        map["PROOT_NO_SECCOMP"] = "1"
        map["HOME"] = "/root"
        map["TMPDIR"] = "/tmp"
        map["LANG"] = "C.UTF-8"
        map["LC_ALL"] = "C.UTF-8"
        map["PATH"] = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
        map["TERM"] = "xterm-256color"
        map["TZ"] = "Asia/Shanghai"
        return map
    }

    fun baseArgs(rootfs: String = Paths.rootfs.absolutePath): MutableList<String> {
        val args = mutableListOf<String>()
        args.add(binary().absolutePath)
        args.add("--kill-on-exit")
        args.add("--link2symlink")
        args.add("-0")
        args.add("-r")
        args.add(rootfs)
        args.add("-b")
        args.add("/dev")
        args.add("-b")
        args.add("/proc")
        args.add("-b")
        args.add("/sys")
        args.add("-b")
        args.add("/sdcard")
        args.add("-b")
        args.add("/storage")
        args.add("-b")
        args.add("/mnt")
        return args
    }

    fun updateResolvConf(ctx: Context) {
        try {
            val cm = ctx.getSystemService(ConnectivityManager::class.java)
            val network = cm?.activeNetwork
            val dns = network?.let { cm.getLinkProperties(it)?.dnsServers }?.mapNotNull { it.hostAddress } ?: emptyList()
            val sb = StringBuilder()
            sb.append("# Generated by McPanel\n")
            if (dns.isNotEmpty()) {
                dns.forEach { sb.append("nameserver ").append(it).append('\n') }
            } else {
                sb.append("nameserver 223.5.5.5\n")
                sb.append("nameserver 119.29.29.29\n")
            }
            if (!dns.contains("223.5.5.5")) sb.append("nameserver 223.5.5.5\n")
            val etc = File(Paths.rootfs, "etc")
            FileUtils.ensureDir(etc)
            // Ubuntu base ships /etc/resolv.conf as a symlink to systemd-resolved (missing
            // target inside the container). Delete the link itself before writing a real file.
            val resolv = File(etc, "resolv.conf")
            try {
                // unlink works on the symlink itself even when its target is missing
                resolv.delete()
            } catch (_: Throwable) {
            }
            resolv.writeText(sb.toString())
            resolv.setReadable(true, false)
            val hosts = File(etc, "hosts")
            hosts.writeText("127.0.0.1 localhost\n127.0.1.1 mcserver\n::1 localhost ip6-localhost ip6-loopback\n")
            hosts.setReadable(true, false)
        } catch (_: Throwable) {
        }
    }

    fun prepareRuntimeDirs() {
        listOf("tmp", "root", "dev", "proc", "sys", "opt", "etc").forEach {
            FileUtils.ensureDir(File(Paths.rootfs, it))
        }
        val tmp = File(Paths.rootfs, "tmp")
        tmp.setReadable(true, false)
        tmp.setWritable(true, true)
        tmp.setExecutable(true, false)
    }

    fun runJavaVersion(javaHome: String, timeoutSec: Long = 120): Shell.ProcResult {
        val cmd = baseArgs()
        cmd.add("-w")
        cmd.add("/root")
        cmd.add("$javaHome/bin/java")
        cmd.add("-version")
        return Shell.run(cmd, env(), Paths.files, timeoutSec)
    }

    fun parseVersion(output: String): String? {
        val m = Regex("version \"([^\"]+)\"").find(output) ?: return null
        return m.groupValues[1]
    }

    fun javaArgs(profile: ServerProfile): MutableList<String> {
        val args = mutableListOf<String>()
        val ram = profile.ramMb.coerceIn(256, 16384)
        args.add("-Xms${(ram / 2).coerceAtLeast(256)}M")
        args.add("-Xmx${ram}M")
        args.add("-Dfile.encoding=UTF-8")
        args.add("-Djava.awt.headless=true")
        args.add("-Duser.language=zh")
        args.add("-Duser.country=CN")
        args.add("-Duser.timezone=Asia/Shanghai")
        args.add("-Dterminal.jline=false")
        args.add("-Dterminal.ansi=false")
        args.add("-XX:+UseG1GC")
        args.add("-XX:MaxGCPauseMillis=200")
        args.add("-XX:+ParallelRefProcEnabled")
        args.add("-XX:+DisableExplicitGC")
        val extra = profile.extraArgs.trim()
        if (extra.isNotEmpty()) {
            extra.split(Regex("\\s+")).filter { it.isNotBlank() }.forEach { args.add(it) }
        }
        args.add("-jar")
        args.add(profile.jar)
        args.add("nogui")
        return args
    }

    /** Full command used to start the server through proot. */
    fun serverCommand(profile: ServerProfile, runtime: JavaRuntime): List<String> {
        val cmd = baseArgs(runtime.rootfs.ifBlank { Paths.rootfs.absolutePath })
        cmd.add("-b")
        cmd.add("${profile.dir}:${profile.dir}")
        cmd.add("-w")
        cmd.add(profile.dir)
        cmd.add("${runtime.javaHome}/bin/java")
        cmd.addAll(javaArgs(profile))
        return cmd
    }

    /** Full command used to start the server with a native (Android bionic) JRE. */
    fun nativeServerCommand(profile: ServerProfile, runtime: JavaRuntime): List<String> {
        val cmd = mutableListOf<String>()
        cmd.add(runtime.javaBinHost)
        cmd.addAll(javaArgs(profile))
        return cmd
    }

    fun nativeEnv(runtime: JavaRuntime): MutableMap<String, String> {
        val map = mutableMapOf<String, String>()
        val home = File(runtime.javaHome)
        val candidates = listOf(
            File(home, "lib"),
            File(home, "lib/server"),
            File(home, "lib/jli"),
            File(home, "lib/aarch64"),
            File(home, "lib/aarch64/jli"),
            File(home, "lib/aarch64/server")
        ).filter { it.isDirectory }
        map["LD_LIBRARY_PATH"] = candidates.joinToString(":") { it.absolutePath }
        map["HOME"] = runtime.javaHome
        map["TMPDIR"] = Paths.tmp.absolutePath
        map["LANG"] = "C.UTF-8"
        return map
    }
}
